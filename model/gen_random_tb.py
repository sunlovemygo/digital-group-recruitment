# -*- coding: utf-8 -*-
"""
gen_random_tb.py —— 生成随机比对 testbench：tb/tb_attention_random.v
用法：python model/gen_random_tb.py [N]     默认 N=100

流程：随机生成 N 组 Q/K/V（种子固定 2026，可复现）→ 用 golden_model.attention
现算期望 O → 全部内嵌进 Verilog tb（1D 展平数组，避开 iverilog 2D 数组坑）→
驱动 attention_ip（你的提交版）→ 采集 4 拍 out_valid 与期望比对。

运行（填完 TODO 后）：
    python model/gen_random_tb.py 100
    iverilog -g2005 -Wall -o build\tb_random.vvp tb\tb_attention_random.v rtl\attention_ip.v
    vvp -n build\tb_random.vvp
或直接双击 sim_random.bat
"""
import os
import sys
import random

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import golden_model as gm

S, D = 8, 4
OUT = os.path.join(HERE, "..", "tb", "tb_attention_random.v")


def vs(v):
    """有符号整数 → 8'sd 字面量（iverilog 接受 -8'sd1，不接受 8'sd-1）"""
    if v < 0:
        return "-8'sd%d" % (-v)
    return "8'sd%d" % v


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 100
    rnd = random.Random(2026)  # 固定种子，复现/报告用
    vecs = []
    for c in range(n):
        q = [rnd.randint(-128, 127) for _ in range(D)]
        k = [[rnd.randint(-128, 127) for _ in range(D)] for _ in range(S)]
        v = [[rnd.randint(-128, 127) for _ in range(D)] for _ in range(S)]
        r = gm.attention(q, k, v)
        gm.check_range(r, v)   # O 必须在 V 列范围内，越界说明算法有 bug
        vecs.append((q, k, v, r["O"]))

    QN = 4 * n
    KN = 32 * n

    L = []
    L.append("`timescale 1ns / 1ps")
    L.append("// AUTO-GENERATED by gen_random_tb.py —— 请勿手工编辑，重跑脚本即可")
    L.append("// DUT = attention_ip（你的提交版），期望来自 golden_model.attention（v2 对齐）")
    L.append("module tb_attention_random;")
    L.append("    reg clk = 1'b0;")
    L.append("    reg rst_n = 1'b0;")
    L.append("    reg start = 1'b0;")
    L.append("    reg q_valid = 1'b0, kv_valid = 1'b0;")
    L.append("    reg signed [7:0] q_in = 8'sd0, k_in = 8'sd0, v_in = 8'sd0;")
    L.append("    wire data_ready, out_valid, done;")
    L.append("    wire signed [7:0] out_data;")
    L.append("    attention_ip dut (.clk(clk), .rst_n(rst_n), .start(start),")
    L.append("        .q_in(q_in), .k_in(k_in), .v_in(v_in),")
    L.append("        .q_valid(q_valid), .kv_valid(kv_valid),")
    L.append("        .data_ready(data_ready), .out_data(out_data),")
    L.append("        .out_valid(out_valid), .done(done));")
    L.append("    always #5 clk = ~clk;")
    L.append("    integer i, j, cc, errors, total;")
    L.append("    localparam N = %d;" % n)
    L.append("    reg signed [7:0] qmem [0:%d];" % (QN - 1))
    L.append("    reg signed [7:0] Kmem [0:%d];" % (KN - 1))
    L.append("    reg signed [7:0] Vmem [0:%d];" % (KN - 1))
    L.append("    reg signed [7:0] Omem [0:%d];" % (QN - 1))
    L.append("    reg signed [7:0] got [0:3];")
    L.append("    integer ocnt;")
    L.append("")
    L.append("    initial begin")
    for idx, (q, k, v, O) in enumerate(vecs):
        L.append("        // vec %d" % idx)
        for d in range(4):
            L.append("        qmem[%d] = %s;" % (idx * 4 + d, vs(q[d])))
        for t in range(8):
            for d in range(4):
                L.append("        Kmem[%d] = %s;" % (idx * 32 + t * 4 + d, vs(k[t][d])))
        for t in range(8):
            for d in range(4):
                L.append("        Vmem[%d] = %s;" % (idx * 32 + t * 4 + d, vs(v[t][d])))
        for d in range(4):
            L.append("        Omem[%d] = %s;" % (idx * 4 + d, vs(O[d])))
    L.append("    end")
    L.append("")
    L.append("    task send_q;")
    L.append("        input integer idx;")
    L.append("        begin")
    L.append("            for (j = 0; j < 4; j = j + 1) begin")
    L.append("                while (!data_ready) @(posedge clk);")
    L.append("                q_in <= qmem[idx*4 + j]; q_valid <= 1'b1; @(posedge clk);")
    L.append("            end")
    L.append("            q_valid <= 1'b0;")
    L.append("        end")
    L.append("    endtask")
    L.append("    task send_kv;")
    L.append("        input integer idx;")
    L.append("        begin")
    L.append("            for (j = 0; j < 32; j = j + 1) begin")
    L.append("                while (!data_ready) @(posedge clk);")
    L.append("                k_in <= Kmem[idx*32 + j]; v_in <= Vmem[idx*32 + j]; kv_valid <= 1'b1; @(posedge clk);")
    L.append("            end")
    L.append("            kv_valid <= 1'b0;")
    L.append("        end")
    L.append("    endtask")
    L.append("")
    L.append("    initial begin")
    L.append("        $dumpfile(\"build/random.vcd\");")
    L.append("        $dumpvars(0, tb_attention_random);")
    L.append("        errors = 0; total = 0;")
    L.append("        repeat (3) @(posedge clk);")
    L.append("        rst_n = 1'b1;")
    L.append("        for (i = 0; i < N; i = i + 1) begin")
    L.append("            @(posedge clk);")
    L.append("            while (!data_ready) @(posedge clk);")
    L.append("            start <= 1'b1; @(posedge clk); start <= 1'b0;")
    L.append("            send_q(i); send_kv(i);")
    L.append("            ocnt = 0; cc = 0;")
    L.append("            while (ocnt < 4 && cc < 5000) begin")
    L.append("                @(posedge clk); cc = cc + 1;")
    L.append("                if (out_valid) begin got[ocnt] = out_data; ocnt = ocnt + 1; end")
    L.append("            end")
    L.append("            total = total + 1;")
    L.append("            if (ocnt < 4) begin")
    L.append("                errors = errors + 1;")
    L.append("                $display(\"[FAIL] vec %0d : 未收到 4 拍 out_valid (cc=%0d)\", i, cc);")
    L.append("            end else if (got[0]!=Omem[i*4+0] || got[1]!=Omem[i*4+1] ||")
    L.append("                       got[2]!=Omem[i*4+2] || got[3]!=Omem[i*4+3]) begin")
    L.append("                errors = errors + 1;")
    L.append("                $display(\"[FAIL] vec %0d got=[%0d,%0d,%0d,%0d] exp=[%0d,%0d,%0d,%0d]\",")
    L.append("                    i, got[0],got[1],got[2],got[3], Omem[i*4+0],Omem[i*4+1],Omem[i*4+2],Omem[i*4+3]);")
    L.append("            end")
    L.append("        end")
    L.append("        if (errors == 0) $display(\"==== RANDOM TEST PASS : %0d/%0d vectors ====\", total, total);")
    L.append("        else             $display(\"==== RANDOM TEST FAIL : %0d/%0d vectors ====\", total-errors, total);")
    L.append("        $finish;")
    L.append("    end")
    L.append("    initial begin #20000000; $display(\"[FAIL] global timeout\"); $finish; end")
    L.append("endmodule")

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print("已生成 %s，共 %d 组随机向量（种子 2026）" % (OUT, n))


if __name__ == "__main__":
    main()
